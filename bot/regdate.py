def _unix(date: str) -> int:
    return int(_dt.datetime.strptime(date, "%Y-%m-%d").timestamp())


ANCHORS = tuple((uid, _unix(date)) for uid, date in _RAW)
FIRST_ID, FIRST_AT = ANCHORS[0]
LAST_ID, LAST_AT = ANCHORS[-1]


def estimate(user_id: int) -> dict | None:
    """{'at': unix, 'low': unix, 'high': unix, 'after': bool} или None.

    low/high — соседние якоря: настоящая дата лежит между ними, и насколько
    широка эта вилка, видно сразу. after=True — id новее последнего якоря,
    тогда известно только «позже такого-то».
    """
    if user_id <= 0:
        return None                      # чаты и каналы живут в другом диапазоне
    if user_id >= LAST_ID:
        return {"at": LAST_AT, "low": LAST_AT, "high": None, "after": True}

    previous = ANCHORS[0]
    for anchor_id, anchor_at in ANCHORS:
        if anchor_id >= user_id:
            low_id, low_at = previous
            span = anchor_id - low_id
            share = (user_id - low_id) / span if span else 0
            return {"at": round(low_at + (anchor_at - low_at) * share),
                    "low": low_at, "high": anchor_at, "after": False}
        previous = (anchor_id, anchor_at)
    return None


def month_in(unix: int) -> str:
    when = _dt.datetime.fromtimestamp(unix)
    return f"{MONTHS_IN[when.month - 1]} {when.year}"


def month_of(unix: int) -> str:
    when = _dt.datetime.fromtimestamp(unix)
    return f"{MONTHS_OF[when.month - 1]} {when.year}"


WIDE = 180 * 86400       # вилка шире полугода — попадание в месяц случайное


def words(user_id: int) -> str:
    """Готовая строка для карточки или пустая, если сказать нечего."""
    guess = estimate(user_id)
    if guess is None:
        return ""
    if guess["after"]:
        return f"заведён после {month_of(guess['at'])}"

    text = f"заведён примерно в {month_in(guess['at'])}"
    if guess["high"] - guess["low"] > WIDE:
        text += (f" _(точнее — от {month_of(guess['low'])} "
                 f"до {month_of(guess['high'])})_")
    return text
